但是曼賽爾表色系基本色相的明度和彩度值不統一，因此在配色時有不易調和及對照的缺點。

4 PCCS表色系（實用配色體系）
1.來源：1951年日本財團法人色彩研究所參照曼賽爾表色系制定「日本色研表色系」並發行色票，1964年色彩研究所依據此體系再開發新的色彩體系，
稱為實用配色體系（Practical Color Co-ordinate SYStem，簡稱PCCS）。

2.色相與色相環：
         （1）以「接近」色光三原色與色料三原色的光譜色，即「紅、橙、黃、綠、藍、紫」6色相為基礎，加入4個中間色，此10色相又再細分成為24色色相環。
         （2）色相環兼顧了色光和色料的實用性，色相環直徑相對的二色屬於「心理補色」關係，但並非光學上的物理補色。

3.明度、彩度與色立體：
         （1）明度階段分為9階，以9.5代表明度最高的白色，以1.5代表明度最低的黑色。彩度階段分為9階，以9S代表彩度最高的純色，以1S代表最低的彩度。
         （2）彩度愈高的色彩，其位置愈遠離中心軸，因為各純色明度不一（但彩度同為9S），使各等色相面純色的高低位置也不同，因此色立體形成不對稱的斜橢圓形，俯視（由上往下看）則為圓形。

4.表色法：表色法為「H-V-C」（色相-明度-彩度），例如純紅色是2R-4.5-9S，2R是指紅色在24色色相環第2號的位置，4.5是明度值，9是彩度值，S為Saturation（飽和度）的縮寫，彩度為9S的色彩均為純色，公式可表示為：








5.色調：
         （1）PCCS表色系的色調（Tone）概念是參考1955年美國色彩協議會暨國家標準局（ISCC-NBS）的「色名稱呼法」而制定。
         （2）PCCS表色系最大的特色是將「明度、彩度」合成色調（Tone）概念，將有彩色分為12種色調，無彩色分為5種色調，每個色調在各等色相面中都有固定位置與意象，例如離色立體中心軸最遠、半橢圓形最尖端的是鮮色調，是等色相面中「彩度最高、最鮮艷」的色彩。
         （3）色調的概念使色彩易於瞭解和表示，方便我們更正確地傳達色彩，「紅」是色相，「鮮、淺、暗」就是形容明度、彩度變化的色調概念，因此PCCS表色法也可以簡單的「色調+色環色相碼」表示，例如v2表示鮮紅色，v12表示鮮綠色，lt20表示淺藍紫色。

6.特色：
         （1）綜合歐美色彩體系之優點，並加以修正為具配色實用性的色彩體系。
         （2）將明度與彩度轉化為色調（Tone）的概念，使符號、色名、色調可相互運用表示，易於表達、瞭解和運用色彩。
         （3）大量出版評價色票，方便色彩教學及色彩計畫、調查、配色之應用。

